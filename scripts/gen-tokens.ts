import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Generates the two stylesheets the app builds on from the design-system export (design/ is read-only):
 *   app/tokens.css  design/tokens/{colors,typography,spacing,base}.css as they are, plus the @font-face rules
 *                   pointed at /fonts (the export's own fonts.css uses relative paths). `base.css` goes into
 *                   `@layer base` so Tailwind utilities (the admin) still win over its element rules.
 *   app/theme.css   the Tailwind v4 `@theme inline` mapping built from tokens.json, so `bg-paper text-ink
 *                   text-body rounded-sm` resolve to the CSS variables (and follow `[data-theme]`).
 * `--check` writes nothing and fails when the committed files differ (CI / unit test).
 */
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (rel: string) => readFileSync(path.join(ROOT, rel), "utf8");

const HEADER = "/* GENERATED by scripts/gen-tokens.ts from design/tokens. Do not edit: change design/ and run `npm run tokens:gen`. */\n";

type Tokens = {
  color: Record<string, unknown>;
  font: Record<string, string>;
  type: Record<string, unknown>;
  radius: Record<string, string>;
  ease: Record<string, string>;
};

export function buildTokensCss(): string {
  const fonts = read("design/tokens/fonts.css").replaceAll("../fonts/", "/fonts/");
  const base = read("design/tokens/base.css").trim();
  return [
    HEADER,
    "/* --- fonts (self-hosted, OFL; /fonts is public/fonts) --- */",
    fonts.trim(),
    "/* --- colors --- */",
    read("design/tokens/colors.css").trim(),
    "/* --- typography --- */",
    read("design/tokens/typography.css").trim(),
    "/* --- spacing, radius, shadow, motion, z --- */",
    read("design/tokens/spacing.css").trim(),
    "/* --- base element rules (in a layer so utilities win in the admin) --- */",
    `@layer base {\n${base}\n}`,
    "",
  ].join("\n");
}

export function buildThemeCss(): string {
  const t = JSON.parse(read("design/tokens/tokens.json")) as Tokens;
  const ref = (name: string) => `  ${name}: var(${name});`;
  const lines: string[] = [];
  lines.push("  /* colors */", ...Object.keys(t.color).map((n) => ref(`--color-${n}`)));
  lines.push("  /* fonts */", ...Object.keys(t.font).map((n) => ref(`--font-${n}`)));
  lines.push("  /* type scale: --text-<name> + --text-<name>--line-height, so text-display-xl, text-body ... resolve */");
  for (const n of Object.keys(t.type)) lines.push(ref(`--text-${n}`), ref(`--text-${n}--line-height`));
  lines.push("  /* radius */", ...Object.keys(t.radius).map((n) => ref(`--radius-${n}`)));
  lines.push("  /* motion */", ...Object.keys(t.ease).map((n) => ref(`--ease-${n}`)));
  lines.push("  /* 4px base: p-1 = 4px ... p-36 = 144px */", "  --spacing: 4px;");
  return `${HEADER}@theme inline {\n${lines.join("\n")}\n}\n`;
}

const OUTPUTS: Array<[string, () => string]> = [
  ["app/tokens.css", buildTokensCss],
  ["app/theme.css", buildThemeCss],
];

if (process.argv[1] && path.basename(process.argv[1]) === "gen-tokens.ts") {
  const check = process.argv.includes("--check");
  let stale = false;
  for (const [file, build] of OUTPUTS) {
    const next = build();
    const target = path.join(ROOT, file);
    let current = "";
    try {
      current = readFileSync(target, "utf8");
    } catch {
      // not generated yet
    }
    if (check) {
      if (current.replaceAll("\r\n", "\n") !== next) {
        console.error(`${file} is out of date. Run: npm run tokens:gen`);
        stale = true;
      }
    } else {
      writeFileSync(target, next);
      console.log(`wrote ${file}`);
    }
  }
  if (stale) process.exit(1);
}
