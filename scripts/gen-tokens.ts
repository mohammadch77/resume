import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Generates the two stylesheets the app builds on from design/tokens.json (the one source of the look, v2):
 *   app/tokens.css  the CSS custom properties, the @font-face rules (Estedad, self-hosted from /fonts = public/fonts), the base
 *                   element rules (in `@layer base` so Tailwind utilities, the admin's, still win).
 *   app/theme.css   the Tailwind v4 `@theme inline` mapping, so `bg-paper text-ink text-body rounded-md` resolve to the variables.
 * `--check` writes nothing and fails when the committed files differ (CI / unit test).
 */
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (rel: string) => readFileSync(path.join(ROOT, rel), "utf8");

const HEADER = "/* GENERATED by scripts/gen-tokens.ts from design/tokens.json. Do not edit: change the JSON and run `npm run tokens:gen`. */\n";

export type Tokens = {
  color: Record<string, string>;
  font: Record<string, string>;
  weight: Record<string, number>;
  type: Record<string, { size: string; lineHeight: string }>;
  radius: Record<string, string>;
  ease: Record<string, string>;
  duration: Record<string, string>;
  z: Record<string, number>;
  layout: Record<string, string>;
  space: Record<string, string>;
};

export const loadTokens = (): Tokens => JSON.parse(read("design/tokens.json")) as Tokens;

const FONT_FACES = [
  '@font-face{font-family:"Estedad";src:url("/fonts/Estedad-Regular.woff2") format("woff2");font-weight:400;font-style:normal;font-display:swap}',
  '@font-face{font-family:"Estedad";src:url("/fonts/Estedad-SemiBold.woff2") format("woff2");font-weight:600;font-style:normal;font-display:swap}',
];

const BASE = `*,*::before,*::after{box-sizing:border-box}
html{background:var(--color-paper);color:var(--color-ink);font-family:var(--font-sans);font-weight:var(--font-weight-regular);line-height:var(--text-body--line-height);-webkit-text-size-adjust:100%;text-rendering:optimizeLegibility}
/* The landing's root size: rem + vw, so browser zoom and the user's font-size setting both still scale it (WCAG 1.4.4). The admin keeps the browser default. */
:root:has(.lm-root){font-size:clamp(15px,calc(0.6rem + 0.45vw),22px)}
body{margin:0;font-size:var(--text-body)}
a{color:var(--color-accent-ink);text-underline-offset:0.3em;text-decoration-thickness:1px}
::selection{background:var(--color-accent);color:var(--color-on-accent)}
:focus-visible{outline:var(--focus-width) solid var(--color-focus-ring);outline-offset:var(--focus-offset)}
.gw-visually-hidden{position:absolute!important;inline-size:1px;block-size:1px;overflow:hidden;clip-path:inset(50%);white-space:nowrap}
@media (prefers-reduced-motion:reduce){*,*::before,*::after{animation-duration:1ms!important;animation-iteration-count:1!important;transition-duration:1ms!important;scroll-behavior:auto!important}}`;

export function buildTokensCss(): string {
  const t = loadTokens();
  const vars: string[] = [];
  for (const [n, v] of Object.entries(t.color)) vars.push(`--color-${n}:${v};`);
  for (const [n, v] of Object.entries(t.font)) vars.push(`--font-${n}:${v};`);
  for (const [n, v] of Object.entries(t.weight)) vars.push(`--font-weight-${n}:${v};`);
  for (const [n, v] of Object.entries(t.type)) vars.push(`--text-${n}:${v.size};--text-${n}--line-height:${v.lineHeight};`);
  for (const [n, v] of Object.entries(t.radius)) vars.push(`--radius-${n}:${v};`);
  for (const [n, v] of Object.entries(t.ease)) vars.push(`--ease-${n}:${v};`);
  for (const [n, v] of Object.entries(t.duration)) vars.push(`--duration-${n}:${v};`);
  for (const [n, v] of Object.entries(t.z)) vars.push(`--z-${n}:${v};`);
  for (const [n, v] of Object.entries(t.layout)) vars.push(`--${n}:${v};`);
  for (const [n, v] of Object.entries(t.space)) vars.push(`--space-${n}:${v};`);
  return [
    HEADER,
    "/* --- fonts (self-hosted, OFL: Estedad by the Estedad Project Authors; /fonts is public/fonts) --- */",
    ...FONT_FACES,
    "/* --- tokens --- */",
    `:root{\n${vars.join("\n")}\n}`,
    "/* --- base element rules (in a layer so utilities win in the admin) --- */",
    `@layer base {\n${BASE}\n}`,
    "",
  ].join("\n");
}

export function buildThemeCss(): string {
  const t = loadTokens();
  const ref = (name: string) => `  ${name}: var(${name});`;
  const lines: string[] = [];
  lines.push("  /* colors */", ...Object.keys(t.color).map((n) => ref(`--color-${n}`)));
  lines.push("  /* fonts */", ...Object.keys(t.font).map((n) => ref(`--font-${n}`)));
  lines.push("  /* type scale: --text-<name> + --text-<name>--line-height, so text-display-xl, text-body ... resolve */");
  for (const n of Object.keys(t.type)) lines.push(ref(`--text-${n}`), ref(`--text-${n}--line-height`));
  lines.push("  /* radius */", ...Object.keys(t.radius).map((n) => ref(`--radius-${n}`)));
  lines.push("  /* motion */", ...Object.keys(t.ease).map((n) => ref(`--ease-${n}`)));
  lines.push("  /* 4px base: p-1 = 4px ... p-36 = 144px (the admin's; the landing uses rem in its own CSS) */", "  --spacing: 4px;");
  return `${HEADER}@theme inline {\n${lines.join("\n")}\n}\n`;
}

const OUTPUTS: Array<[string, () => string]> = [
  ["app/tokens.css", buildTokensCss],
  ["app/theme.css", buildThemeCss],
];

if (process.argv[1] && path.basename(process.argv[1]) === "gen-tokens.ts") {
  const check = process.argv.includes("--check");
  let stale = false;
  for (const [file, build] of OUTPUTS) {
    const next = build();
    const target = path.join(ROOT, file);
    let current = "";
    try {
      current = readFileSync(target, "utf8");
    } catch {
      // not generated yet
    }
    if (check) {
      if (current.replaceAll("\r\n", "\n") !== next) {
        console.error(`${file} is out of date. Run: npm run tokens:gen`);
        stale = true;
      }
    } else {
      writeFileSync(target, next);
      console.log(`wrote ${file}`);
    }
  }
  if (stale) process.exit(1);
}
